#!/usr/bin/env python3
"""Prepare art dropped into assets/ for the game.

Run from the swarajya folder:   python3 tools/build_assets.py

Reads   assets/portraits, assets/buildings, assets/nature, assets/terrain, assets/ui
Writes  assets/built/...  and  assets/manifest.js  (the list the game loads)

Buildings and nature are expected on a flat magenta (#FF00FF) background, which is removed here.
"""
import os, sys, json
from PIL import Image, ImageChops

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets')
OUT = os.path.join(ROOT, 'built')
EXT = ('.png', '.jpg', '.jpeg', '.webp')
SIZE = {'tc': 4, 'house': 2, 'kothar': 2, 'vakhar': 2, 'smith': 2, 'barracks': 3, 'range': 3, 'stable': 3, 'siege': 3, 'market': 3, 'temple': 3, 'tower': 1}
NATURE_W = {'bush': 46, 'gold': 60, 'stone': 60}


def key_magenta(im):
    """Remove a magenta background and the pink fringe it leaves on edges."""
    im = im.convert('RGB')
    r, g, b = im.split()
    k = ImageChops.subtract(ImageChops.darker(r, b), g)          # how magenta each pixel is
    alpha = k.point(lambda v: 255 - max(0, min(255, (v - 36) * 6)))
    spill = k.point(lambda v: int(v * 0.85))
    r = ImageChops.subtract(r, spill)
    b = ImageChops.subtract(b, spill)
    out = Image.merge('RGBA', (r, g, b, alpha))
    box = alpha.point(lambda v: 255 if v > 24 else 0).getbbox()
    return out.crop(box) if box else out


def fit_w(im, w):
    return im.resize((int(w), max(1, round(im.height * w / im.width))), Image.LANCZOS)


def build():
    made = []
    for cat in ('portraits', 'buildings', 'nature', 'terrain', 'ui'):
        src = os.path.join(ROOT, cat)
        if not os.path.isdir(src):
            continue
        os.makedirs(os.path.join(OUT, cat), exist_ok=True)
        for fn in sorted(os.listdir(src)):
            name, ext = os.path.splitext(fn)
            if ext.lower() not in EXT:
                continue
            im = Image.open(os.path.join(src, fn))
            if cat == 'portraits':
                im = im.convert('RGB'); s = min(im.size)
                l, t = (im.width - s) // 2, max(0, (im.height - s) // 4)
                im = im.crop((l, t, l + s, t + s)).resize((256, 256), Image.LANCZOS)
                rel = f'{cat}/{name}.jpg'; im.save(os.path.join(OUT, rel), quality=90)
            elif cat == 'buildings':
                typ = name.split('_', 1)[-1]
                if typ not in SIZE:
                    print('  skipped (unknown building name):', fn); continue
                im = fit_w(key_magenta(im), SIZE[typ] * 64 * 1.1)
                rel = f'{cat}/{name}.png'; im.save(os.path.join(OUT, rel))
            elif cat == 'nature':
                im = key_magenta(im)
                if name.startswith('tree'):
                    im = im.resize((max(1, round(im.width * 104 / im.height)), 104), Image.LANCZOS)
                    if im.width > 96: im = fit_w(im, 96)
                else:
                    im = fit_w(im, NATURE_W.get(name, 60))
                rel = f'{cat}/{name}.png'; im.save(os.path.join(OUT, rel))
            elif cat == 'terrain':
                im = im.convert('RGB'); s = min(im.size)
                im = im.crop((0, 0, s, s)).resize((384, 384), Image.LANCZOS)
                rel = f'{cat}/{name}.jpg'; im.save(os.path.join(OUT, rel), quality=90)
            else:
                im = im.convert('RGB')
                if im.width > 1920: im = fit_w(im, 1920)
                rel = f'{cat}/{name}.jpg'; im.save(os.path.join(OUT, rel), quality=88)
            made.append(rel); print('  ok', rel, im.size)
    with open(os.path.join(ROOT, 'manifest.js'), 'w') as f:
        f.write('/* generated by tools/build_assets.py */\nwindow.SWARAJYA_ASSETS = ' + json.dumps(made, indent=1) + ';\n')
    print(f'{len(made)} asset(s) listed in assets/manifest.js')


if __name__ == '__main__':
    build()
